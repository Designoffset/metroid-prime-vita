# Generates no-op definitions for every WebGPU C function that webgpu_vita's
# sources don't implement. Usage: gen_stubs.py webgpu.h out.cpp src1.cpp [src2.cpp ...]
import re, sys

hdr = open(sys.argv[1]).read()
out_path = sys.argv[2]
defined = set()
for path in sys.argv[3:]:
    src = open(path).read()
    if 'extern "C"' not in src:
        continue
    body = src.split('extern "C" {', 1)[1]
    # function definitions: a return type, the name, a parameter list and an opening brace
    defined |= set(re.findall(r'^\w[\w \*]*?\b(wgpu[A-Za-z0-9]+)\s*\([^;{]*\)\s*\{', body, re.M | re.S))
handles = set(re.findall(r'typedef struct WGPU\w+Impl\* (WGPU\w+)', hdr))
out = ['// Generated by gen_stubs.py: default no-op implementations.', '#include "wv.hpp"', 'extern "C" {']
n = 0
for m in re.finditer(r'^WGPU_EXPORT (.+?) (wgpu\w+)\((.*?)\) WGPU_FUNCTION_ATTRIBUTE;', hdr, re.M):
    ret, name, params = m.group(1).replace('WGPU_NULLABLE ', '').strip(), m.group(2), m.group(3).replace('WGPU_NULLABLE ', '')
    if name in defined:
        continue
    plist = [] if params.strip() in ('', 'void') else [p.strip() for p in params.split(',')]
    sig = ', '.join(plist) if plist else 'void'
    if name.endswith('AddRef'):
        body = '{ wv::addref(%s); }' % plist[0].split()[-1]
    elif name.endswith('Release'):
        body = '{ wv::release(%s); }' % plist[0].split()[-1]
    elif ret == 'void':
        body = '{}'
    elif ret in handles:
        body = '{ return (%s) new wv::Obj(wv::Kind::Generic); }' % ret
    elif ret == 'WGPUStatus':
        body = '{ return WGPUStatus_Success; }'
    elif ret == 'WGPUFuture':
        body = '{ return WGPUFuture{0}; }'
    else:
        body = '{ return {}; }'
    out.append('%s %s(%s) %s' % (ret, name, sig, body))
    n += 1
out.append('}')
open(out_path, 'w').write('\n'.join(out) + '\n')
print('webgpu_vita: generated', n, 'stubs;', len(defined), 'implemented')
