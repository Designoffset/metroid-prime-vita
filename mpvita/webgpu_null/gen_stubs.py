import re, sys
hdr = open(sys.argv[1]).read()
core = open(sys.argv[2]).read()
defined = set(re.findall(r'\b(wgpu[A-Za-z0-9]+)\s*\(', core.split('extern "C" {',1)[1]))
handles = set(re.findall(r'typedef struct WGPU\w+Impl\* (WGPU\w+)', hdr))
out = ['// Generated by gen_stubs.py: default no-op implementations.', '#include "webgpu_null.hpp"', 'using namespace wgnull;', 'extern "C" {']
n = 0
for m in re.finditer(r'^WGPU_EXPORT (.+?) (wgpu\w+)\((.*?)\) WGPU_FUNCTION_ATTRIBUTE;', hdr, re.M):
    ret, name, params = m.group(1).replace('WGPU_NULLABLE ', '').strip(), m.group(2), m.group(3).replace('WGPU_NULLABLE ', '')
    if name in defined: continue
    pnames = []
    plist = [] if params.strip() in ('', 'void') else [p.strip() for p in params.split(',')]
    sig = ', '.join(plist) if plist else 'void'
    if name.endswith('AddRef'):
        body = '{ addref(%s); }' % plist[0].split()[-1]
    elif name.endswith('Release'):
        body = '{ release(%s); }' % plist[0].split()[-1]
    elif ret == 'void':
        body = '{}'
    elif ret in handles:
        body = '{ return (%s)make(ObjKind::Generic); }' % ret
    elif ret == 'WGPUStatus':
        body = '{ return WGPUStatus_Success; }'
    elif ret == 'WGPUFuture':
        body = '{ return WGPUFuture{0}; }'
    else:
        body = '{ return {}; }'
    # silence unused-parameter warnings by dropping names is unnecessary; keep signature
    out.append('%s %s(%s) %s' % (ret, name, sig, body)); n += 1
out.append('}')
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
print('generated', n, 'stubs;', len(defined), 'hand-written')
